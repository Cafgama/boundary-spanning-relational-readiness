% ANALYZE_GRAPH_LEVEL_COMPARISON
% Reproduces paired graph-level comparisons across architectures.
%
% No simulations are executed by this script.

clear;
clc;

addpath('../src');

input_file = [ ...
  '../results/processed/graph_level/', ...
  'combined_graph_summary_NG50_NT50.mat' ...
];

assert(exist(input_file, 'file') == 2, ...
  ['Combined graph-level file not found: ', input_file]);

data = load(input_file);

assert(isfield(data, 'all_GS'), ...
  'Combined file must contain all_GS.');

all_GS = data.all_GS;

GS_baseline = get_architecture_summary(all_GS, 'baseline');
GS_random = get_architecture_summary(all_GS, 'random_bridging');
GS_boundary = get_architecture_summary(all_GS, 'boundary_spanning');

% -------------------------------------------------
% Controlled structural checks: RB versus BS
% -------------------------------------------------
assert(isequal(GS_random.graph_id, GS_boundary.graph_id), ...
  'RB and BS graph identifiers must match.');

assert(max(abs(GS_random.total_edges - ...
               GS_boundary.total_edges)) < 1e-12, ...
  'RB and BS must have equal total edges by paired graph.');

assert(max(abs(GS_random.mean_degree - ...
               GS_boundary.mean_degree)) < 1e-12, ...
  'RB and BS must have equal mean degree by paired graph.');

assert(max(abs(GS_random.total_boundary_edges - ...
               GS_boundary.total_boundary_edges)) < 1e-12, ...
  'RB and BS must have equal boundary-edge counts.');

% -------------------------------------------------
% Analysis settings
% -------------------------------------------------
metrics = {
  'T_cens_mean',
  'T_cens_median',
  'T_cens_p90',
  'T_cens_p95'
};

comparisons_x = {
  GS_baseline,
  GS_random,
  GS_baseline
};

comparisons_y = {
  GS_random,
  GS_boundary,
  GS_boundary
};

comparison_labels = {
  'baseline_minus_random',
  'random_minus_boundary',
  'baseline_minus_boundary'
};

n_boot = 10000;
base_seed = 24680;

n_comparisons = length(comparison_labels);
n_metrics = length(metrics);

all_comparisons = cell(n_comparisons, n_metrics);

% -------------------------------------------------
% Run paired comparisons
% -------------------------------------------------
fprintf('\n============================================================\n');
fprintf('PAIRED GRAPH-LEVEL COMPARISON\n');
fprintf('============================================================\n');
fprintf('Graphs per architecture: %d\n', length(GS_baseline.graph_id));
fprintf('Bootstrap samples: %d\n', n_boot);
fprintf('============================================================\n');

for c = 1:n_comparisons
  fprintf('\n------------------------------------------------------------\n');
  fprintf('%s\n', comparison_labels{c});
  fprintf('------------------------------------------------------------\n');

  fprintf('%-16s %12s %12s %12s %12s %12s %10s\n', ...
    'Metric', ...
    'Mean_X', ...
    'Mean_Y', ...
    'Difference', ...
    'CI_lower', ...
    'CI_upper', ...
    'Y_lower');

  for m = 1:n_metrics
    seed_cm = base_seed + 100 * c + m;

    C = compare_graph_metric( ...
      comparisons_x{c}, ...
      comparisons_y{c}, ...
      metrics{m}, ...
      n_boot, ...
      seed_cm);

    C.comparison_label = comparison_labels{c};

    all_comparisons{c, m} = C;

    fprintf('%-16s %12.2f %12.2f %12.2f %12.2f %12.2f %9.3f\n', ...
      C.metric, ...
      C.mean_x, ...
      C.mean_y, ...
      C.mean_difference, ...
      C.ci_lower, ...
      C.ci_upper, ...
      C.fraction_y_lower);
  end
end

% -------------------------------------------------
% Export analysis CSV
% -------------------------------------------------
output_dir = '../results/processed/analysis';
ensure_dir(output_dir);

timestamp = datestr(now(), 'yyyymmdd_HHMMSS');

output_csv = fullfile(output_dir, ...
  ['paired_graph_comparison_', timestamp, '.csv']);

output_mat = fullfile(output_dir, ...
  ['paired_graph_comparison_', timestamp, '.mat']);

fid = fopen(output_csv, 'w');

assert(fid ~= -1, ...
  ['Could not create output CSV: ', output_csv]);

fprintf(fid, [ ...
  'comparison,architecture_x,architecture_y,metric,n_pairs,', ...
  'mean_x,mean_y,mean_difference,median_difference,', ...
  'relative_reduction,ci_lower,ci_upper,n_x_greater,', ...
  'n_x_lower,n_equal,fraction_y_lower,min_difference,', ...
  'max_difference\n' ...
]);

for c = 1:n_comparisons
  for m = 1:n_metrics
    C = all_comparisons{c, m};

    fprintf(fid, ...
      ['"%s","%s","%s","%s",%d,', ...
       '%.10g,%.10g,%.10g,%.10g,%.10g,', ...
       '%.10g,%.10g,%d,%d,%d,%.10g,%.10g,%.10g\n'], ...
      C.comparison_label, ...
      C.architecture_x, ...
      C.architecture_y, ...
      C.metric, ...
      C.n_pairs, ...
      C.mean_x, ...
      C.mean_y, ...
      C.mean_difference, ...
      C.median_difference, ...
      C.relative_reduction, ...
      C.ci_lower, ...
      C.ci_upper, ...
      C.n_x_greater, ...
      C.n_x_lower, ...
      C.n_equal, ...
      C.fraction_y_lower, ...
      C.min_difference, ...
      C.max_difference);
  end
end

fclose(fid);

save(output_mat, ...
  'all_comparisons', ...
  'metrics', ...
  'comparison_labels', ...
  'n_boot', ...
  'base_seed');

fprintf('\n============================================================\n');
fprintf('ANALYSIS COMPLETED\n');
fprintf('CSV:\n%s\n', output_csv);
fprintf('MAT:\n%s\n', output_mat);
fprintf('============================================================\n');
